test('Verify Quantity Discounts tooltip content and visibility on hover', async ({ page }) => {
  await setupLocalStorageAndMocks(page);

  // Set standard desktop viewport size
  await page.setViewportSize({ width: 1280, height: 1000 });

  // Goto create page
  await page.goto('http://localhost:3000/organizer/dashboard/events/create');

  // Wait for hydration and page to be ready
  await page.waitForTimeout(5000);

  // Click Next three times to go to Tickets step (sub-step 4 is Tickets in step 1 of details)
  const nextButton = page.locator('button:has-text("Next")').first();
  await nextButton.waitFor({ state: 'visible' });
  await nextButton.click(); // Now on sub-step 2 of Details
  await page.waitForTimeout(2000);

  await nextButton.click(); // Now on sub-step 3 of Details
  await page.waitForTimeout(2000);

  await nextButton.click(); // Now on sub-step 4 of Details (Tickets)
  await page.waitForTimeout(2000);

  // Check that default ticket contains the Quantity Discounts header
  const quantityDiscountHeader = page.locator('h6:has-text("Quantity Discounts")').first();
  await expect(quantityDiscountHeader).toBeVisible();

  // Find the discount tooltip container/trigger
  const tooltipTrigger = page.locator('.group\\/discount-tooltip').first();
  await expect(tooltipTrigger).toBeVisible();

  // Hover over the tooltip trigger
  await tooltipTrigger.hover();
  await page.waitForTimeout(500);

  // Assert tooltip popover is visible and contains expected content
  const tooltipTextContainer = tooltipTrigger.locator('.absolute.bottom-full');
  await expect(tooltipTextContainer).toBeVisible();

  const tooltipText = await tooltipTextContainer.innerText();
  expect(tooltipText).toContain("Offer automatic discounts when attendees purchase multiple tickets.");
  expect(tooltipText).toContain("For example, buy 5 tickets and get 10% off.");

  // Save a nice screenshot of the tooltip in action
  await tooltipTrigger.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'tests/verify_quantity_discounts_tooltip.png' });
});
